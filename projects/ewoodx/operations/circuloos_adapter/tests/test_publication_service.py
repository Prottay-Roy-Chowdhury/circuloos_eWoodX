"""Offline tests for CIRCULOOS publication service.

Requires existing local mappings generated by:
    test_mapping_service.py

No authentication, network requests, or live publication.
"""

from __future__ import annotations

from copy import deepcopy
import json
from pathlib import Path
import sys

REPOSITORY_ROOT = Path(__file__).resolve().parents[5]
sys.path.insert(0, str(REPOSITORY_ROOT))

from projects.ewoodx.operations.circuloos_adapter.publication_service import (
    CirculoosPublicationService,
)

from projects.ewoodx.operations.circuloos_adapter.tests.test_entity_registry import (
    WORKSPACE_NAME,
    TIMBER_ID,
    load_entity_manager,
)


def main():

    entity_manager = load_entity_manager(
        WORKSPACE_NAME
    )

    service = CirculoosPublicationService(
        entity_manager=entity_manager,
        allow_live=False,
    )

    registry = service.registry

    before = registry.load(TIMBER_ID)

    if before is None:
        raise RuntimeError(
            "No CIRCULOOS registry. "
            "Run test_mapping_service.py first."
        )

    print("\n========================================")
    print("CIRCULOOS PUBLICATION SERVICE TEST")
    print("OFFLINE MODE")
    print("========================================")

    # ----------------------------------------------------------
    # 1. Preview Wood
    # ----------------------------------------------------------

    wood = service.preview_wood(TIMBER_ID)

    assert wood["urn"] == before["wood"]["urn"]
    assert wood["entity_type"] == "wood"
    assert wood["payload_path"].is_file()
    assert isinstance(wood["payload"], list)
    assert len(wood["payload"]) == 1

    print("\n[1] Wood preview: PASS")
    print("Wood URN:", wood["urn"])
    print("Quantity:", wood["payload"][0]["quantity"])

    # ----------------------------------------------------------
    # 2. Preview AD-001
    # ----------------------------------------------------------

    ad = service.preview_advertisement(
        TIMBER_ID,
        sequence=1,
    )

    assert ad["sequence"] == 1
    assert ad["entity_type"] == "others"
    assert ad["wood_urn"] == wood["urn"]
    assert ad["payload_path"].is_file()

    assert (
        ad["payload"][0]["refMaterial"]["object"]
        == wood["urn"]
    )

    assert (
        ad["payload"][0]["materialQuantity"]["value"]
        == wood["payload"][0]["quantity"]["value"]
    )

    print("\n[2] Advertisement preview: PASS")
    print("Advertisement URN:", ad["urn"])
    print("refMaterial:", ad["wood_urn"])

    # ----------------------------------------------------------
    # 3. Confirm live publication is disabled
    # ----------------------------------------------------------

    try:
        service.publish_wood(TIMBER_ID)
    except PermissionError:
        print("\n[3] Wood publication blocked: PASS")
    else:
        raise AssertionError(
            "Wood publication was not blocked."
        )

    try:
        service.publish_advertisement(
            TIMBER_ID,
            sequence=1,
        )
    except PermissionError:
        print("[4] Advertisement publication blocked: PASS")
    else:
        raise AssertionError(
            "Advertisement publication was not blocked."
        )

    # ----------------------------------------------------------
    # 4. Verify missing advertisement is rejected
    # ----------------------------------------------------------

    try:
        service.preview_advertisement(
            TIMBER_ID,
            sequence=999,
        )
    except ValueError:
        print("[5] Unknown advertisement rejected: PASS")
    else:
        raise AssertionError(
            "Unknown advertisement was not rejected."
        )

    # ----------------------------------------------------------
    # 5. Verify preview returns detached data
    # ----------------------------------------------------------

    original_wood = json.loads(
        wood["payload_path"].read_text(
            encoding="utf-8"
        )
    )

    modified = deepcopy(wood["payload"])
    modified[0]["quantity"]["value"] = 999.0

    assert json.loads(
        wood["payload_path"].read_text(
            encoding="utf-8"
        )
    ) == original_wood

    print("[6] Local payload unchanged: PASS")

    # ----------------------------------------------------------
    # 6. Verify registry unchanged
    # ----------------------------------------------------------

    after = registry.load(TIMBER_ID)

    assert after == before

    assert after["wood"]["status"] == "local_only"

    ad_record = next(
        item
        for item in after["advertisements"]
        if item["sequence"] == 1
    )

    assert ad_record["status"] == "local_only"

    print("[7] Registry unchanged: PASS")

    # ----------------------------------------------------------
    # 7. Final result
    # ----------------------------------------------------------

    print("\n========================================")
    print("PUBLICATION SERVICE TEST: PASS")
    print("NO NETWORK REQUESTS PERFORMED")
    print("========================================")


if __name__ == "__main__":
    main()